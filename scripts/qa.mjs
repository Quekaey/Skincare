import { chromium } from 'playwright-core';
import { strict as assert } from 'node:assert';

const browser = await chromium.launch({ executablePath: 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
await page.goto('http://localhost:3003', { waitUntil: 'networkidle' });
assert.equal(await page.locator('h1').textContent(), 'Skincare starts with knowing what you need.');
await page.locator('input[name="feel"][value="dry"]').check();
await page.locator('input[name="texture"][value="rich"]').check();
await page.locator('input[name="help"][value="textures"]').check();
await page.getByRole('button', { name: /Show my starting point/ }).click();
assert.match(await page.locator('.finder-result').textContent(), /only contains a lightweight moisturiser/i);
await page.getByRole('button', { name: /Start again/ }).click();
assert.equal(await page.locator('input[name="feel"]:checked').count(), 0);
await page.locator('.product-card').first().getByRole('button', { name: /View Details/ }).click();
assert.equal(await page.getByRole('dialog', { name: /Gentle Daily Cleanser/ }).count(), 1);
await page.keyboard.press('Escape');
assert.equal(await page.getByRole('dialog', { name: /Gentle Daily Cleanser/ }).count(), 0);
await page.getByRole('tab', { name: 'Evening' }).click();
assert.equal(await page.locator('.routine-item').count(), 2);
await page.locator('.product-card').first().getByRole('button', { name: /Add to Basket/ }).click();
assert.match(await page.locator('.basket-foot').textContent(), /₦12,500/);
await page.getByRole('button', { name: 'Increase quantity' }).click();
assert.match(await page.locator('.basket-foot').textContent(), /₦25,000/);
await page.getByRole('button', { name: 'Preview Order' }).click();
assert.match(await page.locator('.demo-order').textContent(), /No order has been placed/);
await page.keyboard.press('Escape');
await page.screenshot({ path: 'desktop-full.png', fullPage: true });
await page.setViewportSize({ width: 390, height: 844 });
await page.reload({ waitUntil: 'networkidle' });
assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth), true);
await page.screenshot({ path: 'mobile-full.png', fullPage: true });
console.log('QA passed: finder, reset, dialog/Escape, tabs, basket quantity/subtotal, preview notice, mobile overflow.');
await browser.close();
